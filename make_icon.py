# -*- coding: utf-8 -*-
"""Иконка приложения: строгий монохром — тёмный круг, белый график."""
from PIL import Image, ImageDraw

S = 256
img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
d = ImageDraw.Draw(img)

# тёмный круг с тонкой светлой окантовкой
d.ellipse((10, 10, S - 10, S - 10), fill=(16, 20, 26, 255))
d.ellipse((10, 10, S - 10, S - 10), outline=(230, 234, 240, 255), width=6)

# белый восходящий график
pts = [(66, 178), (108, 138), (146, 156), (192, 86)]
d.line(pts, fill=(245, 247, 250, 255), width=16, joint="curve")
# стрелка
d.polygon([(196, 76), (160, 88), (184, 116), (206, 112)], fill=(245, 247, 250, 255))
# точки
for x, y in pts[:-1]:
    d.ellipse((x - 9, y - 9, x + 9, y + 9), fill=(245, 247, 250, 255))
# базовая линия
d.line((56, 200, 200, 200), fill=(120, 130, 145, 255), width=8)

img.save("app.ico", sizes=[(16, 16), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
print("app.ico created")
